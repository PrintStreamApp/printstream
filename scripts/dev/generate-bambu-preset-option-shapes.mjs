#!/usr/bin/env node
/**
 * Generates a COMPLETE key -> { vector, stringLike } shape table for every option BambuStudio's
 * `PrintConfig.cpp` defines via `this->add(...)`.
 *
 * WHY THIS EXISTS: `packages/shared/src/bambu-preset-codec.ts` converts between Bambu Cloud's
 * serialized `ConfigOption::serialize()` string form and a local preset's array form. Getting an
 * option's shape wrong mis-encodes it SILENTLY: a numeric vector treated as string-like gets
 * c-style-quoted and semicolon-joined instead of comma-joined, corrupting the value on push (and
 * leaving it un-split on pull). The codec used to fall back to a hand-maintained exception list
 * (`UNCATALOGUED_OPTION_SHAPES`) for options the per-kind settings catalogs omit (filament/process/
 * machine-settings.generated.ts are scoped to what their TUNE DIALOG exposes, not to round-trip
 * fidelity), and that list kept missing real options (`hotend_cooling_rate`, `nozzle_flush_dataset`,
 * `physical_extruder_map`, `grab_length`, `hotend_heating_rate`, none of them in any per-kind
 * catalog or the exception list). This generator scans literally every `this->add()` in the
 * vendored source instead, so a newly-vendored BambuStudio option is covered automatically on the
 * next regeneration rather than silently falling through to a guessed shape.
 *
 * A handful of keys the codec also needs (`name`, `version`, `from`, `filament_id`) are NOT
 * `PrintConfig` options (`filament_id` in particular is read via a runtime `dynamic_cast` rather
 * than declared with `this->add()`), so those stay a small manual list in the codec itself; this
 * generator only ever emits what it can verify from the source.
 *
 * Usage:
 *   node scripts/dev/generate-bambu-preset-option-shapes.mjs [--src <bambustudio-src>]
 *
 * Output: packages/shared/src/generated/bambu-preset-option-shapes.generated.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { indexOptionBlocks, mapType } from './lib/bambu-config-parse.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..', '..')

/**
 * The `mapType` field types whose serialized form is c-style-escaped and semicolon-joined
 * (matching `bambu-preset-codec.ts`'s own `STRING_LIKE_TYPES`) rather than comma-joined.
 */
const STRING_LIKE_FIELD_TYPES = new Set(['string', 'enum', 'point'])

function parseArgs(argv) {
  let src = path.join(repoRoot, 'tmp', 'bambustudio-src')
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--src') src = path.resolve(argv[++i])
  }
  return { src }
}

function main() {
  const { src } = parseArgs(process.argv.slice(2))
  const printConfigPath = path.join(src, 'src', 'libslic3r', 'PrintConfig.cpp')
  let content
  try {
    content = readFileSync(printConfigPath, 'utf8')
  } catch {
    console.error(`Could not read ${printConfigPath}. Pass --src <bambustudio-src>.`)
    process.exit(1)
  }

  const { blocks } = indexOptionBlocks(content)

  const shapes = {}
  for (const [key, { coType }] of blocks) {
    const { fieldType, vector } = mapType(coType)
    shapes[key] = { vector, stringLike: STRING_LIKE_FIELD_TYPES.has(fieldType) }
  }

  const sortedKeys = Object.keys(shapes).sort()
  const lines = sortedKeys.map((key) => `  ${JSON.stringify(key)}: { vector: ${shapes[key].vector}, stringLike: ${shapes[key].stringLike} }`)

  const outDir = path.join(repoRoot, 'packages', 'shared', 'src', 'generated')
  mkdirSync(outDir, { recursive: true })
  const outPath = path.join(outDir, 'bambu-preset-option-shapes.generated.ts')
  const header = `/**
 * GENERATED by scripts/dev/generate-bambu-preset-option-shapes.mjs: do not edit.
 *
 * Every option BambuStudio's \`PrintConfig.cpp\` defines (${sortedKeys.length} keys), mapped to
 * whether it is a VECTOR option and whether its elements are STRING-LIKE (c-style-escaped,
 * semicolon-joined) as opposed to numeric/boolean (comma-joined). Consumed by
 * \`bambu-preset-codec.ts\` to convert between Bambu Cloud's serialized \`ConfigOption::serialize()\`
 * string form and a local preset's array form without guessing at an unrecognized option's shape.
 *
 * Complete by construction: scans every \`this->add()\` in the vendored source rather than a
 * hand-maintained exception list, so re-running after vendoring a newer BambuStudio is what keeps
 * this current, not remembering to add a key by hand.
 */
export const BAMBU_PRESET_OPTION_SHAPES: Readonly<Record<string, { vector: boolean; stringLike: boolean }>> = {
${lines.join(',\n')}
}
`
  writeFileSync(outPath, header)
  console.log(`Wrote ${sortedKeys.length} option shapes to ${outPath}`)
}

main()
