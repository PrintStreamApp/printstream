#!/usr/bin/env node
/**
 * Build the editor Text tool's bundled fonts.
 *
 * The tool extrudes real glyph OUTLINES, so it needs actual font files at runtime, not the CSS
 * webfonts the UI uses (a font loaded through CSS exposes no outlines to script). Shipping the
 * upstream DejaVu faces whole would add ~2.9 MB to the repo and to the public snapshot, almost all
 * of it Unicode coverage nobody engraves on a print. This subsets them to {@link CHARSET} instead,
 * which is the difference between ~2.9 MB and roughly a tenth of that.
 *
 * DejaVu is chosen because its licence permits redistribution and modification (including
 * subsetting) with no reciprocal obligation, and because it ships a matched sans/serif/mono trio.
 * The licence travels with the output; see the copy written beside the fonts.
 *
 * Regenerate after changing the charset or the source faces:
 *   node scripts/dev/generate-text-tool-fonts.mjs
 *
 * The output is committed, so a normal build and the public export need neither this script nor the
 * system fonts it reads.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const OUT_DIR = path.join(ROOT, 'apps/web/public/fonts/text-tool')
const SOURCE_DIR = '/usr/share/fonts/truetype/dejavu'
const LICENSE_SOURCE = '/usr/share/doc/fonts-dejavu-core/copyright'

/**
 * What a subsetted face can render. Printable ASCII plus the Latin-1 letters and the punctuation
 * and symbols people actually engrave (currency, degree, dashes, curly quotes). Anything outside
 * this falls back to "load your own font file", which is why the set can stay small.
 */
const CHARSET = [
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_unused, i) => String.fromCodePoint(0x20 + i)),
  ...Array.from({ length: 0xff - 0xa0 + 1 }, (_unused, i) => String.fromCodePoint(0xa0 + i)),
  '–', '—', '‘', '’', '“', '”', '•', '…',
  '€', '™', '°', '±', '×', '÷'
]

/** family + style -> source file. Styles map onto the tool's Bold / Italic checkboxes. */
const FACES = [
  { family: 'DejaVu Sans', style: 'Regular', file: 'DejaVuSans.ttf', out: 'dejavu-sans.ttf' },
  { family: 'DejaVu Sans', style: 'Bold', file: 'DejaVuSans-Bold.ttf', out: 'dejavu-sans-bold.ttf' },
  { family: 'DejaVu Serif', style: 'Regular', file: 'DejaVuSerif.ttf', out: 'dejavu-serif.ttf' },
  { family: 'DejaVu Serif', style: 'Bold', file: 'DejaVuSerif-Bold.ttf', out: 'dejavu-serif-bold.ttf' },
  { family: 'DejaVu Sans Mono', style: 'Regular', file: 'DejaVuSansMono.ttf', out: 'dejavu-mono.ttf' },
  { family: 'DejaVu Sans Mono', style: 'Bold', file: 'DejaVuSansMono-Bold.ttf', out: 'dejavu-mono-bold.ttf' }
]

async function subsetFace(face) {
  const source = opentype.parse((await readFile(path.join(SOURCE_DIR, face.file))).buffer)
  // Index 0 must be .notdef in any valid font, and it is what renders for an unmapped character.
  const glyphs = [source.glyphs.get(0)]
  const seen = new Set([0])
  for (const character of CHARSET) {
    const glyph = source.charToGlyph(character)
    // charToGlyph falls back to .notdef for anything the source lacks; keeping those would bloat
    // the subset with duplicates of the same empty glyph.
    if (!glyph || glyph.index === 0 || seen.has(glyph.index)) continue
    seen.add(glyph.index)
    glyphs.push(glyph)
  }
  const subset = new opentype.Font({
    familyName: face.family,
    styleName: face.style,
    unitsPerEm: source.unitsPerEm,
    ascender: source.ascender,
    descender: source.descender,
    glyphs
  })
  const bytes = Buffer.from(subset.toArrayBuffer())
  await writeFile(path.join(OUT_DIR, face.out), bytes)
  return { out: face.out, glyphs: glyphs.length, bytes: bytes.length }
}

await mkdir(OUT_DIR, { recursive: true })
let total = 0
for (const face of FACES) {
  const result = await subsetFace(face)
  total += result.bytes
  console.log(`${result.out.padEnd(24)} ${String(result.glyphs).padStart(4)} glyphs  ${(result.bytes / 1024).toFixed(1)} KB`)
}
await writeFile(
  path.join(OUT_DIR, 'LICENSE.txt'),
  `These fonts are subsets of DejaVu, generated by scripts/dev/generate-text-tool-fonts.mjs.\n`
  + `Only the glyph coverage is reduced; the outlines are unmodified.\n\n`
  + (await readFile(LICENSE_SOURCE, 'utf8'))
)
console.log(`total ${(total / 1024).toFixed(1)} KB`)
