/**
 * The About dialog (BRAND-8): product name and version, update status, and the standard links,
 * in the order and wording the shared standard sets (winui-app-kit's `kit.about.*` labels).
 *
 * Opened from the app's main menu (`AboutMenuItem`). It describes and links; it never applies an
 * update or sends anything itself: update state comes from the same query the footer reads, and
 * Support opens the existing Help & feedback dialog, whose own fallback is the support email. The
 * web has no logs folder, so the standard's Diagnostics section is omitted here.
 */
import { useSyncExternalStore } from 'react'
import { Button, DialogTitle, Divider, Link, ModalClose, Stack, Typography } from '@mui/joy'
import { resolveDisplayedAppBuild } from '../lib/appVersionDisplay'
import { describeAboutUpdateStatus } from '../lib/aboutUpdateStatus'
import { isWebUpdatePending, subscribeWebUpdatePending } from '../lib/appStaleness'
import { useInstalledAppBuild, useServerAppVersion } from '../hooks/useAppVersionQueries'
import { BackAwareModal } from './BackAwareModal'
import { ScrollableDialogBody, ScrollableModalDialog } from './ScrollableDialog'

/** The public open-core repository; the hosted product's private parts are not published. */
const SOURCE_CODE_URL = 'https://github.com/PrintStreamApp/printstream'
const LICENSE_URL = `${SOURCE_CODE_URL}/blob/main/LICENSE`
const PRIVACY_POLICY_URL = 'https://printstream.app/privacy'
const TERMS_URL = 'https://printstream.app/terms'
/** Served by the web app itself (generated by `npm run notices`). */
const THIRD_PARTY_NOTICES_PATH = '/THIRD-PARTY-NOTICES.txt'

/** The store tagline, which the About surface repeats (BRAND-8 item 2). */
const TAGLINE = 'Monitor, control, slice, and manage your Bambu Lab printers from anywhere.'

export interface AboutDialogProps {
  onClose: () => void
  /** Which edition is answering; the hosted one also links its Terms of Service. */
  deployment: 'cloud' | 'self-hosted'
  /** Opens Help & feedback. Omitted where that dialog is not offered (platform mode). */
  onOpenSupport?: () => void
}

export function AboutDialog({ onClose, deployment, onOpenSupport }: AboutDialogProps) {
  const { data: serverBuild } = useServerAppVersion()
  const { data: installedApp } = useInstalledAppBuild()
  const reloadPending = useSyncExternalStore(subscribeWebUpdatePending, isWebUpdatePending, () => false)

  const displayedBuild = resolveDisplayedAppBuild(serverBuild)
  const updateStatus = describeAboutUpdateStatus(serverBuild, displayedBuild, reloadPending)

  const openSupport = onOpenSupport
    ? () => {
        onClose()
        onOpenSupport()
      }
    : null

  return (
    <BackAwareModal open onClose={onClose}>
      <ScrollableModalDialog sx={{ width: { xs: '100%', sm: 480 } }}>
        <ModalClose />
        <DialogTitle>About</DialogTitle>
        <ScrollableDialogBody sx={{ mt: 1, p: 0 }}>
          <Stack spacing={2}>
            <Stack direction="row" spacing={1.5} alignItems="center">
              <img src="/icon-192.png" alt="" width={48} height={48} />
              <Stack spacing={0.25} sx={{ minWidth: 0 }}>
                <Typography level="title-lg">PrintStream</Typography>
                <Typography level="body-sm" title={displayedBuild.revision ?? undefined}>
                  Version {displayedBuild.version}
                </Typography>
                {installedApp ? (
                  <Typography level="body-xs" textColor="text.tertiary">
                    {installedApp.label} version {installedApp.version}
                  </Typography>
                ) : null}
              </Stack>
            </Stack>
            <Typography level="body-sm" textColor="text.tertiary">{TAGLINE}</Typography>

            <Divider />
            <Stack spacing={0.5}>
              <Typography level="title-sm">Updates</Typography>
              <Typography level="body-sm" color={updateStatus.attention ? 'warning' : undefined}>
                {updateStatus.message}
              </Typography>
            </Stack>

            <Divider />
            <Stack spacing={0.75}>
              <Typography level="title-sm">Links</Typography>
              <Link href={SOURCE_CODE_URL} target="_blank" rel="noreferrer">Source code</Link>
              <Link href={PRIVACY_POLICY_URL} target="_blank" rel="noreferrer">Privacy policy</Link>
              {openSupport ? (
                <Link component="button" onClick={openSupport} sx={{ alignSelf: 'flex-start' }}>Support</Link>
              ) : null}
              <Link href={LICENSE_URL} target="_blank" rel="noreferrer">License</Link>
              {deployment === 'cloud' ? (
                <Link href={TERMS_URL} target="_blank" rel="noreferrer">Terms of Service</Link>
              ) : null}
              <Link href={THIRD_PARTY_NOTICES_PATH} target="_blank" rel="noreferrer">Third-party notices</Link>
            </Stack>
          </Stack>
        </ScrollableDialogBody>
        <Stack direction="row" justifyContent="flex-end" sx={{ pt: 1.5 }}>
          <Button variant="plain" color="neutral" onClick={onClose}>Close</Button>
        </Stack>
      </ScrollableModalDialog>
    </BackAwareModal>
  )
}
